-- SP1-P2-01: drivers, routes, trips tables

CREATE TYPE driver_status AS ENUM ('AVAILABLE', 'ON_TRIP', 'INACTIVE');

CREATE TABLE drivers (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     BIGINT       NOT NULL REFERENCES transport_companies(id),
    user_id        BIGINT       UNIQUE REFERENCES users(id),
    full_name      VARCHAR(150) NOT NULL,
    phone          VARCHAR(20)  NOT NULL,
    license_number VARCHAR(50)  NOT NULL,
    status         driver_status NOT NULL DEFAULT 'AVAILABLE',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_drivers_company_id ON drivers(company_id);
CREATE INDEX idx_drivers_status     ON drivers(status);

CREATE TABLE routes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id         BIGINT       NOT NULL REFERENCES transport_companies(id),
    name               VARCHAR(200) NOT NULL,
    origin             VARCHAR(200) NOT NULL,
    destination        VARCHAR(200) NOT NULL,
    estimated_minutes  INT          NOT NULL CHECK (estimated_minutes > 0),
    base_fare          DECIMAL(12,2) NOT NULL DEFAULT 0 CHECK (base_fare >= 0),
    description        TEXT,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_routes_company_id ON routes(company_id);

CREATE TYPE trip_status AS ENUM ('DRAFT', 'PUBLISHED', 'FULL', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED');

CREATE TABLE trips (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id        BIGINT        NOT NULL REFERENCES routes(id),
    company_id      BIGINT        NOT NULL REFERENCES transport_companies(id),
    vehicle_id      BIGINT        NOT NULL REFERENCES vehicles(id),
    driver_id       BIGINT        NOT NULL REFERENCES drivers(id),
    departure_time  TIMESTAMPTZ   NOT NULL,
    fare            DECIMAL(12,2) NOT NULL CHECK (fare >= 0),
    note            TEXT,
    status          trip_status   NOT NULL DEFAULT 'DRAFT',
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_trips_company_id      ON trips(company_id);
CREATE INDEX idx_trips_route_id        ON trips(route_id);
CREATE INDEX idx_trips_vehicle_id      ON trips(vehicle_id);
CREATE INDEX idx_trips_driver_id       ON trips(driver_id);
CREATE INDEX idx_trips_departure_time  ON trips(departure_time);
CREATE INDEX idx_trips_status          ON trips(status);

