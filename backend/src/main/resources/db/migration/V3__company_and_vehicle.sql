-- SP1-P1-02: transport_companies and vehicles tables

CREATE TYPE company_status AS ENUM ('PENDING', 'APPROVED', 'REJECTED');
CREATE TYPE vehicle_status AS ENUM ('AVAILABLE', 'IN_USE', 'MAINTENANCE', 'INACTIVE');

CREATE TABLE transport_companies (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id        BIGINT NOT NULL UNIQUE REFERENCES users(id),
    name                 VARCHAR(200) NOT NULL,
    business_license_no  VARCHAR(50)  UNIQUE,
    tax_code             VARCHAR(30),
    address              VARCHAR(500) NOT NULL,
    contact_phone        VARCHAR(20)  NOT NULL,
    contact_email        VARCHAR(255),
    representative_name  VARCHAR(150) NOT NULL,
    business_information TEXT NOT NULL,
    description          TEXT,
    logo_url             VARCHAR(500),
    status               company_status NOT NULL DEFAULT 'PENDING',
    approved_by          BIGINT REFERENCES users(id),
    approved_at          TIMESTAMPTZ,
    reject_reason        VARCHAR(500),
    avg_rating           DECIMAL(3,2)  NOT NULL DEFAULT 0,
    rating_count         INT           NOT NULL DEFAULT 0,
    version              BIGINT        NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX idx_companies_status ON transport_companies(status);

CREATE TABLE vehicles (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id     BIGINT       NOT NULL REFERENCES transport_companies(id),
    plate_number   VARCHAR(20)  NOT NULL UNIQUE,
    vehicle_type   VARCHAR(50)  NOT NULL,
    brand          VARCHAR(50),
    model          VARCHAR(50),
    seat_capacity  INT          NOT NULL CHECK (seat_capacity > 0),
    description    TEXT,
    image_url      VARCHAR(500),
    status         vehicle_status NOT NULL DEFAULT 'AVAILABLE',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_vehicles_company_id ON vehicles(company_id);
CREATE INDEX idx_vehicles_status     ON vehicles(status);
