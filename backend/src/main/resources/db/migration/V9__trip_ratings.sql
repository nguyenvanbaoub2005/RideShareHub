-- SP4-P1-01: Passenger ratings for completed bookings & company rating aggregation

CREATE TABLE ratings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id    BIGINT       NOT NULL UNIQUE REFERENCES bookings(id) ON DELETE CASCADE,
    trip_id       BIGINT       NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    company_id    BIGINT       NOT NULL REFERENCES transport_companies(id) ON DELETE CASCADE,
    driver_id     BIGINT       NOT NULL REFERENCES drivers(id) ON DELETE CASCADE,
    passenger_id  BIGINT       NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    score         INT          NOT NULL CHECK (score BETWEEN 1 AND 5),
    trip_score    INT          NOT NULL CHECK (trip_score BETWEEN 1 AND 5),
    driver_score  INT          NOT NULL CHECK (driver_score BETWEEN 1 AND 5),
    company_score INT          NOT NULL CHECK (company_score BETWEEN 1 AND 5),
    comment       VARCHAR(500) NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_ratings_company ON ratings(company_id, created_at DESC);
CREATE INDEX idx_ratings_driver ON ratings(driver_id);
CREATE INDEX idx_ratings_passenger ON ratings(passenger_id);
