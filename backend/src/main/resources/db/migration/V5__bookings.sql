-- SP2-P2-01 & SP2-P2-02: bookings table and atomic seat reservation tracking on trips

ALTER TABLE trips
    ADD COLUMN booked_seats INT NOT NULL DEFAULT 0 CHECK (booked_seats >= 0),
    ADD COLUMN version BIGINT NOT NULL DEFAULT 0;

CREATE TYPE booking_status AS ENUM (
    'PENDING',
    'CONFIRMED',
    'PICKED_UP',
    'COMPLETED',
    'CANCELLED',
    'NO_SHOW'
);

CREATE TABLE bookings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_code    VARCHAR(20)    NOT NULL UNIQUE,
    trip_id         BIGINT         NOT NULL REFERENCES trips(id),
    passenger_id    BIGINT         NOT NULL REFERENCES users(id),
    idempotency_key VARCHAR(100)   NOT NULL,
    seat_count      INT            NOT NULL CHECK (seat_count > 0),
    pickup_address  VARCHAR(500)   NOT NULL,
    pickup_lat      DECIMAL(10,7),
    pickup_lng      DECIMAL(10,7),
    dropoff_address VARCHAR(500)   NOT NULL,
    dropoff_lat     DECIMAL(10,7),
    dropoff_lng     DECIMAL(10,7),
    estimated_fare  DECIMAL(12,2)  NOT NULL CHECK (estimated_fare >= 0),
    status          booking_status NOT NULL DEFAULT 'CONFIRMED',
    cancel_reason   VARCHAR(500),
    cancelled_at    TIMESTAMPTZ,
    confirmed_at    TIMESTAMPTZ,
    picked_up_at    TIMESTAMPTZ,
    completed_at    TIMESTAMPTZ,
    version         BIGINT         NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uq_bookings_passenger_idempotency UNIQUE (passenger_id, idempotency_key)
);

CREATE INDEX idx_bookings_trip_id          ON bookings(trip_id);
CREATE INDEX idx_bookings_passenger_status ON bookings(passenger_id, status);
CREATE INDEX idx_bookings_trip_status      ON bookings(trip_id, status);

