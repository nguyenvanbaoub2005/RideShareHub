-- SP3-P2-01, SP3-P2-01b, SP3-P2-02: Driver trip execution lifecycle, trip stops, and realtime GPS tracking

ALTER TABLE trips
    ADD COLUMN assignment_status VARCHAR(20) NOT NULL DEFAULT 'ASSIGNED',
    ADD COLUMN accepted_at       TIMESTAMPTZ,
    ADD COLUMN started_at        TIMESTAMPTZ,
    ADD COLUMN completed_at      TIMESTAMPTZ,
    ADD COLUMN last_lat          DECIMAL(10,7),
    ADD COLUMN last_lng          DECIMAL(10,7),
    ADD COLUMN last_heading      DECIMAL(6,2),
    ADD COLUMN last_speed_kmh    DECIMAL(6,2),
    ADD COLUMN last_location_at  TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS trip_stops (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id      BIGINT        NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    booking_id   BIGINT        NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    stop_type    VARCHAR(20)   NOT NULL,
    stop_order   INT           NOT NULL,
    address      VARCHAR(500)  NOT NULL,
    latitude     DECIMAL(10,7),
    longitude    DECIMAL(10,7),
    status       VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
    arrived_at   TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    version      BIGINT        NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_trip_stops_booking_type UNIQUE (booking_id, stop_type)
);

CREATE INDEX IF NOT EXISTS idx_trip_stops_trip_order ON trip_stops(trip_id, stop_order);
CREATE INDEX IF NOT EXISTS idx_trip_stops_booking_id ON trip_stops(booking_id);
